"""Regenerate the JSON-LD structured data blocks from the CMS content files.

Why this exists: events, pricing and the common questions are edited in the
CMS at /admin/, but AI search engines and Google read structured data from
the page source. This script rewrites the JSON-LD in each page so the two
never drift apart.

RUN THIS whenever pricing, events or the FAQ change in a way that matters
for search:

    python tools/build-schema.py

It rewrites everything between the AUTO-SCHEMA markers in each HTML file and
touches nothing else.
"""
import json
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = "https://sctechia.com.au"

START = "<!-- AUTO-SCHEMA:START - generated by tools/build-schema.py, do not hand-edit -->"
END = "<!-- AUTO-SCHEMA:END -->"


def load(name):
    with open(os.path.join(ROOT, 'content', name), encoding='utf-8') as f:
        return json.load(f)


