def price_value(t):
    return t["priceDisplay"].replace(",", "") if t["priceMode"] == "amount" else None


def offers():
    out = []
    for t in pricing:
        offer = {
            "@type": "Offer",
            "name": t["name"] + " membership",
            "description": t["description"],
            "category": "Membership",
            "url": SITE + "/join",
            "availability": "https://schema.org/InStock",
            "seller": {"@id": SITE + "/#org"},
        }
        pv = price_value(t)
        if pv:
            offer["price"] = pv
            offer["priceCurrency"] = "AUD"
            offer["eligibleDuration"] = {"@type": "QuantitativeValue", "value": 1, "unitCode": "ANN"}
        out.append(offer)
    return out


MONTHS = {m: i for i, m in enumerate(
    ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'], 1)}


def parse_date(label):
    """Pull an ISO date out of a human date label like '16 Sep 2026 - All day'.

    Returns None for labels with no real date ('Coming soon', 'Quarterly').
    Schema.org requires a startDate on an Event, so an event without a
    confirmed date is left out rather than published with a fake one.
    """
    m = re.search(r'\b(\d{1,2})\s+([A-Z][a-z]{2})[a-z]*\s+(\d{4})\b', label)
    if not m:
        return None
    day, mon, year = m.group(1), m.group(2), m.group(3)
    if mon not in MONTHS:
        return None
    return '%s-%02d-%02d' % (year, MONTHS[mon], int(day))


def event_items():
    out = []
    for e in events:
        start = parse_date(e.get("dateLabel", ""))
        if not start:
            continue
        ev = {
            "@type": "Event",
            "name": e["title"],
            "description": e["description"],
            "startDate": start,
            "eventAttendanceMode": "https://schema.org/OfflineEventAttendanceMode",
            "eventStatus": "https://schema.org/EventScheduled",
            "location": {"@type": "Place", "name": e["location"],
                         "address": {"@type": "PostalAddress", "addressRegion": "QLD", "addressCountry": "AU"}},
            "organizer": {"@id": SITE + "/#org"},
        }
        if e.get("moreInfoUrl"):
            ev["url"] = e["moreInfoUrl"]
        out.append(ev)
    return out


def faq_page(page_id):
    return {
        "@type": "FAQPage",
        "@id": page_id + "#faq",
        "mainEntity": [
            {"@type": "Question", "name": f["question"],
             "acceptedAnswer": {"@type": "Answer", "text": f["answer"]}}
            for f in faqs
        ],
    }


def breadcrumb(page_url, label):
    return {
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": 1, "name": "Home", "item": SITE + "/"},
            {"@type": "ListItem", "position": 2, "name": label, "item": page_url},
        ],
    }


def block(graph):
    payload = {"@context": "https://schema.org", "@graph": graph}
    return (START + '\n<script type="application/ld+json">\n'
            + json.dumps(payload, indent=2, ensure_ascii=False)
            + '\n</script>\n' + END)


def write_block(filename, graph):
    path = os.path.join(ROOT, filename)
    s = open(path, encoding='utf-8').read()
    new = block(graph)
    if START in s:
        s = re.sub(re.escape(START) + r'.*?' + re.escape(END), lambda _: new, s, flags=re.S)
    else:
        # Replace the first hand-written ld+json block, or insert before </head>
        m = re.search(r'<script type="application/ld\+json">.*?</script>', s, re.S)
        if m:
            s = s[:m.start()] + new + s[m.end():]
        else:
            s = s.replace('</head>', new + '\n</head>')
    open(path, 'w', encoding='utf-8').write(s)
    print('  schema written:', filename)


